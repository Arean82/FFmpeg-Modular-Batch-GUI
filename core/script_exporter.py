"""Queue script exporter for FFmpeg Modular Batch GUI.

Exports queued jobs to a production-grade, standalone executable bash script
for headless server execution, render farms, or cluster nodes.
"""
import os
import shlex
from typing import Any


def generate_batch_bash_script(
    queue_data: list[dict[str, Any]],
    output_path: str,
    parallel_jobs: int = 1,
    app_version: str = "2.1.0"
) -> bool:
    """Generates an executable bash script containing all queued transcode jobs.

    Args:
        queue_data: List of queue item dicts containing input, output, params, extra_params, etc.
        output_path: Destination path for the .sh script.
        parallel_jobs: Concurrency level (1 = sequential, >1 = xargs/background workers).
        app_version: Application release version for script header.

    Returns:
        True on success, False on error.
    """
    try:
        lines = [
            "#!/usr/bin/env bash",
            "# ========================================================================",
            f"# FFmpeg Modular Batch GUI - Automated Export Script (v{app_version})",
            "# Generated by Synora Studio <arean@synorastudio.in>",
            f"# Total Jobs: {len(queue_data)} | Parallel Concurrency: {parallel_jobs}",
            "# ========================================================================",
            "set -eo pipefail",
            "",
            "# Color formatting",
            'GREEN="\\033[0;32m"',
            'YELLOW="\\033[1;33m"',
            'RED="\\033[0;31m"',
            'BLUE="\\033[0;34m"',
            'NC="\\033[0m"',
            "",
            'echo -e "${BLUE}========================================================================${NC}"',
            'echo -e "${BLUE} Starting FFmpeg Batch Processing: Total jobs = ' + str(len(queue_data)) + '${NC}"',
            'echo -e "${BLUE}========================================================================${NC}"',
            "",
            "START_TIME=$(date +%s)",
            "COMPLETED=0",
            "FAILED=0",
            "",
            "# Job transcode execution function",
            "run_transcode_job() {",
            '    local job_id="$1"',
            '    local input_file="$2"',
            '    local output_file="$3"',
            '    shift 3',
            '    local ffmpeg_args=("$@")',
            "",
            '    echo -e "${YELLOW}[Job ${job_id}/${' + str(len(queue_data)) + '}] Transcoding: $(basename "${input_file}")${NC}"',
            '    mkdir -p "$(dirname "${output_file}")"',
            "",
            '    if ffmpeg -hide_banner -y -i "${input_file}" "${ffmpeg_args[@]}" "${output_file}"; then',
            '        echo -e "${GREEN}[Job ${job_id} SUCCESS] -> ${output_file}${NC}"',
            "        return 0",
            "    else",
            '        echo -e "${RED}[Job ${job_id} FAILED] -> ${input_file}${NC}"',
            "        return 1",
            "    fi",
            "}",
            "",
        ]

        if parallel_jobs <= 1:
            # Sequential execution block
            for idx, item in enumerate(queue_data, start=1):
                in_f = item.get("input_file", "")
                out_f = item.get("output_file", "")
                params = item.get("params", "")
                extra = item.get("extra_params", "")

                full_args = f"{params} {extra}".strip()
                # Split args respecting quotes
                try:
                    split_args = shlex.split(full_args)
                except Exception:
                    split_args = full_args.split()

                quoted_args = " ".join(shlex.quote(a) for a in split_args)

                lines.append(f"# Job #{idx}")
                lines.append(
                    f'run_transcode_job "{idx}" {shlex.quote(in_f)} {shlex.quote(out_f)} {quoted_args} && ((COMPLETED++)) || ((FAILED++))'
                )
                lines.append("")
        else:
            # Multi-job parallel execution helper
            lines.extend([
                f"# Export jobs function and parallel runner (max {parallel_jobs} simultaneous jobs)",
                "export -f run_transcode_job",
                "export GREEN YELLOW RED BLUE NC",
                "",
                "cat << 'EOF' | xargs -0 -n 1 -P " + str(parallel_jobs) + " bash -c 'eval \"$0\"'",
            ])
            for idx, item in enumerate(queue_data, start=1):
                in_f = item.get("input_file", "")
                out_f = item.get("output_file", "")
                params = item.get("params", "")
                extra = item.get("extra_params", "")
                full_args = f"{params} {extra}".strip()
                try:
                    split_args = shlex.split(full_args)
                except Exception:
                    split_args = full_args.split()
                quoted_args = " ".join(shlex.quote(a) for a in split_args)

                job_cmd = f'run_transcode_job "{idx}" {shlex.quote(in_f)} {shlex.quote(out_f)} {quoted_args}\0'
                lines.append(job_cmd)
            lines.extend([
                "EOF",
                "",
            ])

        lines.extend([
            "END_TIME=$(date +%s)",
            "DURATION=$((END_TIME - START_TIME))",
            'echo -e "${BLUE}========================================================================${NC}"',
            'echo -e "${BLUE} All tasks complete in ${DURATION}s.${NC}"',
            'echo -e "${BLUE}========================================================================${NC}"',
        ])

        with open(output_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")

        # Make executable (chmod +x)
        os.chmod(output_path, 0o755)
        return True
    except Exception as e:
        print(f"Error generating bash export script: {e}")
        return False
